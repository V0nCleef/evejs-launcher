def _format_fields(value: str) -> tuple[str, ...]:
    """Return named format fields while rejecting positional placeholders."""

    fields: list[str] = []
    for _literal, field_name, _format_spec, _conversion in Formatter().parse(value):
        if field_name is None:
            continue
        if not field_name or field_name.isdigit():
            raise RuntimeError(f"Russian UI catalog has positional placeholder: {value!r}")
        fields.append(field_name)
    return tuple(sorted(fields))


